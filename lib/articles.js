/**
 * Resolve an article's localized fields (title, description) with fallback to FR.
 */
function resolveLocale(article, locale = 'fr') {
  if (!article) return null;
  const localized = article[locale] || article.fr;
  return { ...article, title: localized.title, description: localized.description };
}

export function getArticleBySlug(slug, locale = 'fr') {
  const article = articles.find(a => a.slug === slug);
  return resolveLocale(article, locale);
}

export function getRelatedArticles(slug, count = 3, locale = 'fr') {
  const current = articles.find(a => a.slug === slug);
  if (!current) return articles.slice(0, count).map(a => resolveLocale(a, locale));
  return articles
    .filter(a => a.slug !== slug)
    .sort((a, b) => (a.category === current.category ? -1 : 1))
    .slice(0, count)
    .map(a => resolveLocale(a, locale));
}

export function formatDate(dateStr, locale = 'fr') {
  return new Date(dateStr).toLocaleDateString(
    locale === 'en' ? 'en-US' : 'fr-FR',
    { day: 'numeric', month: 'long', year: 'numeric' }
  );
}

/**
 * Get all articles with localized fields resolved (for listing pages).
 */
export function getAllArticles(locale = 'fr') {
  return articles
    .map(a => resolveLocale(a, locale))
    .sort((a, b) => (a.date || '').localeCompare(b.date || ''));
}
